-- Automatic sales-reconciliation items (revenue accounts 4x): credit notes, medicine cost reversed on revenue, year-end closing.
SELECT TO_CHAR(VM_DATE,'YYMM')||';'||K||';'||ROUND(SUM(DR_AMOUNT),2)||';'||ROUND(SUM(CR_AMOUNT),2) R FROM (
 SELECT VM_DATE,DR_AMOUNT,CR_AMOUNT, CASE WHEN DESCRIPTION LIKE 'VAT_CREDIT_NOTE%' THEN 'VCN' WHEN DESCRIPTION LIKE 'CREDIT_NOTE%' THEN 'CN'
   WHEN DESCRIPTION LIKE 'ادوية عن شهر%' THEN 'MED' ELSE 'X' END K
 FROM {P}GL_TRANSACTIONS_DETAILS WHERE VM_DATE>=DATE '{D0}' AND VM_DATE<DATE '{D1}' AND STATUS IN ('P','O') AND ACCOUNT_NO LIKE '4%'
   AND NVL(DESCRIPTION,'x') NOT LIKE '%قفال الحسابات الختامية%') WHERE K<>'X' GROUP BY TO_CHAR(VM_DATE,'YYMM'),K ORDER BY 1;
-- Rent invoiced with VAT (add-back): 4300003 credits in vouchers that also touch 21230071
SELECT TO_CHAR(T.VM_DATE,'YYMM')||';'||ROUND(SUM(T.CR_AMOUNT),2) R FROM {P}GL_TRANSACTIONS_DETAILS T
WHERE T.VM_DATE>=DATE '{D0}' AND T.VM_DATE<DATE '{D1}' AND T.STATUS IN ('P','O') AND T.ACCOUNT_NO='4300003'
  AND EXISTS (SELECT 1 FROM {P}GL_TRANSACTIONS_DETAILS V WHERE V.VOUCHER_NO=T.VOUCHER_NO AND V.ACCOUNT_NO='21230071' AND V.STATUS IN ('P','O'))
GROUP BY TO_CHAR(T.VM_DATE,'YYMM') ORDER BY 1
