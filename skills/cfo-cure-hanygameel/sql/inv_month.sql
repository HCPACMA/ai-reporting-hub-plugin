SELECT YM, ROUND(SUM(NET),2) NET FROM (
 SELECT TO_CHAR(M.PATIENT_INVOICE_DATE,'YYYYMM') YM, SUM(NVL(C.BILL_AMOUNT,0)-NVL(C.BILL_DISCOUNT,0)-NVL(C.VAT_AMT,0)-DECODE(C.BILL_TO,'P',0,NVL(C.BILL_PATIENT_SHARE,0))) NET
 FROM {P}RC_PATIENT_INVOICES M, {P}RC_PATIENT_INVOICE_CHARGES C
 WHERE M.ORGANIZATION_NO=C.ORGANIZATION_NO AND M.PATIENT_INVOICE_NO=C.PATIENT_INVOICE_NO
   AND M.STATUS='P' AND C.STATUS='P' AND C.BILL_TO IN ('C','G','P')
   AND M.PATIENT_INVOICE_DATE>=DATE '{D0}' AND M.PATIENT_INVOICE_DATE<DATE '{D1}'
 GROUP BY TO_CHAR(M.PATIENT_INVOICE_DATE,'YYYYMM')
 UNION ALL
 SELECT TO_CHAR(R.REFUND_INVOICE_DATE,'YYYYMM'), -SUM(NVL(C.BILL_AMOUNT,0)-NVL(C.BILL_DISCOUNT,0)-NVL(C.VAT_AMT,0)-DECODE(C.BILL_TO,'P',0,NVL(C.BILL_PATIENT_SHARE,0)))
 FROM {P}RC_PATIENT_REFUND_INVOICES R, {P}RC_PATIENT_RETURN_INV_CHARGES C
 WHERE R.ORGANIZATION_NO=C.ORGANIZATION_NO AND R.REFUND_INVOICE_NO=C.REFUND_INVOICE_NO
   AND C.STATUS='P' AND R.STATUS='P' AND C.BILL_TO IN ('C','G','P')
   AND R.REFUND_INVOICE_DATE>=DATE '{D0}' AND R.REFUND_INVOICE_DATE<DATE '{D1}'
 GROUP BY TO_CHAR(R.REFUND_INVOICE_DATE,'YYYYMM')
) GROUP BY YM ORDER BY 1
