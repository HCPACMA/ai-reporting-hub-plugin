-- Ledger-held balances of one branch database (job bd_bal in refresh.py). {P} = '' or 'EXSYS.'; {D1..D4} = year-ends, {D5} = last closed day.
SELECT SUBSTR(T.ACCOUNT_NO,1,3) G,
 SUM(CASE WHEN T.VM_DATE<=DATE '{D1}' THEN T.DR_AMOUNT-T.CR_AMOUNT END) A1,
 SUM(CASE WHEN T.VM_DATE<=DATE '{D2}' THEN T.DR_AMOUNT-T.CR_AMOUNT END) A2,
 SUM(CASE WHEN T.VM_DATE<=DATE '{D3}' THEN T.DR_AMOUNT-T.CR_AMOUNT END) A3,
 SUM(CASE WHEN T.VM_DATE<=DATE '{D4}' THEN T.DR_AMOUNT-T.CR_AMOUNT END) A4,
 SUM(CASE WHEN T.VM_DATE<=DATE '{D5}' THEN T.DR_AMOUNT-T.CR_AMOUNT END) A5,
 SUM(T.DR_AMOUNT-T.CR_AMOUNT) ALLD
FROM {P}GL_TRANSACTIONS_DETAILS T
WHERE T.STATUS<>'C' AND (T.ACCOUNT_NO LIKE '1%' OR T.ACCOUNT_NO LIKE '2%') AND T.VOUCHER_NO<>'JV1-24/04043'
GROUP BY SUBSTR(T.ACCOUNT_NO,1,3) ORDER BY 1
