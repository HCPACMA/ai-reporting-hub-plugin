-- Names of the customer groups / customers used by credit notes. Output R: G;no;name  or  C;no;name
SELECT 'G;'||g.CUSTOMER_GROUP_NO||';'||REPLACE(g.DESCRIPTION_P,';',',') R FROM {P}CUSTOMER_GROUPS g WHERE g.CUSTOMER_GROUP_NO IN (SELECT CUSTOMER_GROUP_NO FROM {P}AR_CREDIT_NOTE_M)
UNION ALL
SELECT 'C;'||c.ACCOUNT_NO||';'||REPLACE(c.DESCRIPTION_P,';',',') FROM {P}CUSTOMERS c WHERE c.ACCOUNT_NO IN (SELECT CUSTOMER_NO FROM {P}AR_CREDIT_NOTE_M)
