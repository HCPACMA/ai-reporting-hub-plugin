-- Expense accounts monthly: YYMM:DR:CR:lines:manual_lines per account.
SELECT ACCOUNT_NO||'|'||MAX(ACCOUNT_ARB_NAME)||'|'||LISTAGG(YM||':'||DR||':'||CR||':'||N||':'||NJ,',') WITHIN GROUP (ORDER BY YM) R FROM (
 SELECT ACCOUNT_NO, MAX(ACCOUNT_ARB_NAME) ACCOUNT_ARB_NAME, TO_CHAR(VM_DATE,'YYMM') YM, ROUND(SUM(DR_AMOUNT),2) DR, ROUND(SUM(CR_AMOUNT),2) CR,
        COUNT(*) N, SUM(CASE WHEN VM_TYPE='J' THEN 1 ELSE 0 END) NJ
 FROM {P}GL_TRANSACTIONS_DETAILS WHERE VM_DATE>=DATE '{D0}' AND VM_DATE<DATE '{D1}' AND STATUS IN ('P','O') AND ACCOUNT_TYPE='Expenses'
   AND NVL(DESCRIPTION,'x') NOT LIKE '%قفال الحسابات الختامية%'
 GROUP BY ACCOUNT_NO, TO_CHAR(VM_DATE,'YYMM')) GROUP BY ACCOUNT_NO ORDER BY 1
