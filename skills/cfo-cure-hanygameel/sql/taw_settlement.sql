-- Tawuniya settlement review — ledger side (Cure, branch='ALL', unprefixed; Riyadh alone needs EXSYS.)
-- 1) month-end claim JVs in the settlement period
SELECT TO_CHAR(TRUNC(VM_DATE),'YYYY-MM') MON, MIN(VOUCHER_NO) VNO, ROUND(SUM(DR_AMOUNT),2) DR,
       ROUND(SUM(CASE WHEN DESCRIPTION LIKE '%مرتجع%' OR DESCRIPTION LIKE '%Refund%' THEN CR_AMOUNT END),2) RET,
       ROUND(SUM(CASE WHEN NOT (DESCRIPTION LIKE '%مرتجع%' OR DESCRIPTION LIKE '%Refund%') THEN CR_AMOUNT END),2) ADJ
FROM GL_TRANSACTIONS_DETAILS WHERE ACCOUNT_NO='1240007' AND SUB_ACCOUNT_NO='100001' AND STATUS<>'C'
  AND (DESCRIPTION LIKE '%مريض%' OR DESCRIPTION LIKE '%Outpatient%') AND TRUNC(VM_DATE) BETWEEN DATE '{P0}' AND DATE '{P1}'
GROUP BY TO_CHAR(TRUNC(VM_DATE),'YYYY-MM') ORDER BY 1;
-- 2) receipts / credit notes / closings (month paid is read from the narration)
SELECT VOUCHER_NO, TO_CHAR(TRUNC(VM_DATE),'YYYY-MM-DD') DT, ROUND(DR_AMOUNT,2) DR, ROUND(CR_AMOUNT,2) CR, SUBSTR(REPLACE(DESCRIPTION,CHR(10),' '),1,130) DS
FROM GL_TRANSACTIONS_DETAILS WHERE ACCOUNT_NO='1240007' AND SUB_ACCOUNT_NO='100001' AND STATUS<>'C'
  AND DESCRIPTION NOT LIKE '%مريض%' AND TRUNC(VM_DATE) >= DATE '{P0}' ORDER BY VM_DATE, VOUCHER_NO;
-- 3) balance today
SELECT ROUND(SUM(DR_AMOUNT-CR_AMOUNT),2) BAL FROM GL_TRANSACTIONS_DETAILS WHERE ACCOUNT_NO='1240007' AND SUB_ACCOUNT_NO='100001' AND STATUS<>'C';
