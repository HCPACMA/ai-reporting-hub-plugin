import sys
kind,a,b=sys.argv[1],int(sys.argv[2]),int(sys.argv[3])
def n(c): return f"NVL(TO_CHAR({c},'TM9'),'')"
def d(c,f='YYYY-MM-DD HH24:MI:SS'): return f"NVL(TO_CHAR({c},'{f}'),'')"
def t(c): return f"REPLACE(REPLACE(REPLACE(REPLACE(NVL({c},''),'|',' '),'~',' '),CHR(10),' '),CHR(13),' ')"
if kind=='prod':
    cols=[t('PRODUCT_CODE'),n('INV_GROUP'),n('PRODUCT_CATEGORY'),t('DESCRIPTION_P'),t('PRIMARY_UOM'),t('ACTIVE_FLAG'),n('NEAR_EXPIRY_DAYS'),t('CONTROL_DRUG_FLAG'),n('PRODUCT_AVERAGE_COST'),n('EXTERNAL_COST_PRICE')]
    frm="EXSYS.IM_PRODUCT_MASTER WHERE ACTIVE_FLAG='Y'"; order='PRODUCT_CODE'; K=15
elif kind=='bal':
    cols=[t('PRODUCT_CODE'),t('PRODUCT_NAME'),t('ORGANIZATION_NO'),n('STORE_ID'),t('UOM_CODE'),n('MIN_QTY'),n('REORDER_QTY'),n('MAX_QTY'),n('ONHAND_QTY'),n('INTRANSIT_QTY'),n('RESERVED_QTY'),n('AVAILABLE_QTY')]
    frm="EXSYS.VINV_STORE_PRODUCTS WHERE ONHAND_QTY>0 AND PRODUCT_CODE IN (SELECT PRODUCT_CODE FROM EXSYS.IM_PRODUCT_MASTER WHERE ACTIVE_FLAG='Y')"; order='PRODUCT_CODE, STORE_ID'; K=15
elif kind=='bat':
    cols=[t('ORGANIZATION_NO'),n('STORE_ID'),n('INV_GROUP'),n('PRODUCT_CATEGORY'),t('PRODUCT_CODE'),t('PRODUCT_DESCRIPTION'),t('BATCH_NO'),d('EXPIRY_DATE'),n('NEAR_EXPIRY_DAYS'),t('UOM_DESCRIPTION'),n('QTY_ON_HAND'),n('QTY_ALLOCATED')]
    frm="EXSYS.IM_STORE_PRODUCT_BATCHS_VIEW"; order='ORGANIZATION_NO, STORE_ID, PRODUCT_CODE, BATCH_NO, QTY_ON_HAND'; K=15
elif kind=='mfg':
    cols=[t('PRODUCT_CODE'),t('BATCH_NO'),t('MANF_BATCH_NO'),t('ORGANIZATION_NO')]
    frm="EXSYS.VINV_MFG_BATCH"; order='ORGANIZATION_NO, PRODUCT_CODE, BATCH_NO, MANF_BATCH_NO'; K=40
s="||'|'||".join(cols)
print(f"SELECT g, LISTAGG(s,'~') WITHIN GROUP (ORDER BY n) c, RPAD('.',50,'.') p FROM (SELECT n, FLOOR((n-1)/{K}) g, s FROM (SELECT ROW_NUMBER() OVER (ORDER BY {order}) n, {s} s FROM {frm})) WHERE g BETWEEN {a} AND {b} GROUP BY g ORDER BY g")
